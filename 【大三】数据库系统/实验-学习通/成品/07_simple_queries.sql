USE jwgl2023217273;

-- ----------------------------------------------------------------------------
-- 1. 求计算机应用专业的学生学号和姓名
-- 需要 JOIN Student 和 Class 表，按专业名称筛选
-- ----------------------------------------------------------------------------
SELECT S.Sno, S.Sname
FROM Student S
    JOIN Class C ON S.ClsNO = C.ClsNO
WHERE C.Specialty = '计算机应用';

-- ----------------------------------------------------------------------------
-- 2. 求选修了课程的学生学号
-- 使用 DISTINCT 去重，因为一个学生可能选多门课
-- ----------------------------------------------------------------------------
SELECT DISTINCT Sno
FROM SC;

-- ----------------------------------------------------------------------------
-- 3. 求选修0001课程的学生学号和成绩，按成绩降序排列，成绩相同时按学号升序
-- ORDER BY 多列排序：先按 Grade DESC，再按 Sno ASC
-- ----------------------------------------------------------------------------
SELECT Sno, Grade
FROM SC
WHERE Cno = '0001'
ORDER BY Grade DESC, Sno ASC;

-- ----------------------------------------------------------------------------
-- 4. 求选修0001课程且成绩在80－90之间的学生学号和成绩，并将成绩乘以系数0.75输出
-- BETWEEN 包含边界值 80 和 90
-- 输出计算后的成绩，别名可以清晰表达含义
-- ----------------------------------------------------------------------------
SELECT Sno, Grade, Grade * 0.75 AS AdjustedGrade
FROM SC
WHERE Cno = '0001'
    AND Grade BETWEEN 80 AND 90;

-- ----------------------------------------------------------------------------
-- 5. 求计算机应用和数学专业的姓"张"的学生的信息
-- 使用 LIKE '张%' 匹配以"张"开头的姓名
-- IN 子句筛选多个专业
-- ----------------------------------------------------------------------------
SELECT S.*
FROM Student S
    JOIN Class C ON S.ClsNO = C.ClsNO
WHERE C.Specialty IN ('计算机应用', '数学')
    AND S.Sname LIKE '张%';

-- ----------------------------------------------------------------------------
-- 6. 求缺少了成绩的学生的学号和课程号
-- Grade IS NULL 表示缺考或成绩未录入
-- ----------------------------------------------------------------------------
SELECT Sno, Cno
FROM SC
WHERE Grade IS NULL;
