USE jwgl2023217273;

-- ----------------------------------------------------------------------------
-- 1. 查询每个学生的情况以及他（她）所选修的课程
-- 使用 LEFT JOIN 确保没有选课的学生也出现在结果中
-- ----------------------------------------------------------------------------
SELECT S.*, SC.Cno, SC.Grade
FROM Student S
    LEFT JOIN SC ON S.Sno = SC.Sno
ORDER BY S.Sno, SC.Cno;

-- ----------------------------------------------------------------------------
-- 2. 求学生的学号、姓名、选修的课程名及成绩
-- 三表 JOIN：Student → SC → Course
-- 使用 LEFT JOIN 确保未选课的学生也能显示
-- ----------------------------------------------------------------------------
SELECT S.Sno, S.Sname, C.Cname, SC.Grade
FROM Student S
    LEFT JOIN SC ON S.Sno = SC.Sno
    LEFT JOIN Course C ON SC.Cno = C.Cno
ORDER BY S.Sno, C.Cname;

-- ----------------------------------------------------------------------------
-- 3. 求选修0001课程且成绩在90分以上的学生学号、姓名及成绩
-- 三表 JOIN 后添加 WHERE 筛选条件
-- ----------------------------------------------------------------------------
SELECT S.Sno, S.Sname, SC.Grade
FROM Student S
    JOIN SC ON S.Sno = SC.Sno
WHERE SC.Cno = '0001'
    AND SC.Grade > 90;

-- ----------------------------------------------------------------------------
-- 4. 查询每一门课的间接先行课（即先行课的先行课）
-- 使用自连接（Self Join）：
--   第一次 JOIN 得到直接先行课
--   第二次 JOIN 通过先行课再关联到间接先行课
-- 例如：数据库(0004) → 直接先行课数据结构(0005) → 间接先行课程序设计(0002)
-- ----------------------------------------------------------------------------
SELECT C1.Cno      AS 课程号,
       C1.Cname    AS 课程名,
       C1.Cpno     AS 直接先行课号,
       C2.Cname    AS 直接先行课名,
       C2.Cpno     AS 间接先行课号,
       C3.Cname    AS 间接先行课名
FROM Course C1
    LEFT JOIN Course C2 ON C1.Cpno = C2.Cno     -- 直接先行课
    LEFT JOIN Course C3 ON C2.Cpno = C3.Cno     -- 间接先行课（先行课的先行课）
ORDER BY C1.Cno;
