-- ============================================================================
-- 实验一：建立与删除索引（步骤4、5）
-- 数据库：jwgl2023217273
-- ============================================================================

USE jwgl2023217273;

-- ============================================================================
-- 步骤4：建立索引
-- ============================================================================

-- ----------------------------------------------------------------------------
-- (1) 在 Student 表的 Sname 列上建立普通降序索引
-- 降序索引可用于按姓名降序排序或查找的查询优化
-- MySQL 8.0+ 支持 DESC 索引
-- ----------------------------------------------------------------------------
CREATE INDEX idx_student_sname_desc
    ON Student(Sname DESC);

-- 验证索引
SHOW INDEX FROM Student;

-- ----------------------------------------------------------------------------
-- (2) 在 Course 表的 Cname 列上建立唯一索引
-- 唯一索引确保课程名不重复，同时加速按课程名的查询
-- ----------------------------------------------------------------------------
CREATE UNIQUE INDEX idx_course_cname_unique
    ON Course(Cname);

-- 验证索引
SHOW INDEX FROM Course;

-- ----------------------------------------------------------------------------
-- (3) 在 SC 表的 Sno 列上建立"聚集索引"
-- ★ MySQL/InnoDB 重要说明 ★
-- 在 MySQL 的 InnoDB 存储引擎中，主键（PRIMARY KEY）本身就是聚集索引，
-- 数据按主键顺序物理存储。InnoDB 不支持用户显式创建"聚集索引"。
-- SC 表的主键是 (Sno, Cno)，数据已按此复合主键聚集存储。
-- 由于 Sno 是复合主键的最左前缀，仅按 Sno 查询时也能利用主键索引。
-- 因此这里无需（也无法）创建额外的聚集索引。
-- 如果确实需要加速仅按 Sno 的查询（不涉及 Cno），以下创建普通索引即可：
-- ----------------------------------------------------------------------------
-- CREATE INDEX idx_sc_sno ON SC(Sno);
-- 注：该语句被注释，因为主键索引已覆盖 Sno 的查询需求（最左前缀原则）

-- ----------------------------------------------------------------------------
-- (4) 在 SC 表的 Sno(升序)、Cno(降序)、Grade(升序) 三列上建立普通复合索引
-- 复合索引可优化同时包含学号、课程号和成绩条件的查询
-- ----------------------------------------------------------------------------
CREATE INDEX idx_sc_sno_cno_grade
    ON SC(Sno ASC, Cno DESC, Grade ASC);

-- 验证索引
SHOW INDEX FROM SC;

-- ============================================================================
-- 步骤5：删除索引
-- 删除 Course 表 Cname 列上的唯一索引
-- ============================================================================
DROP INDEX idx_course_cname_unique ON Course;

-- 验证索引已删除
SHOW INDEX FROM Course;
