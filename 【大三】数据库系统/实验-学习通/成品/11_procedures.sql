USE jwgl2023217273;

-- ============================================================================
-- 1. 在班级表 Class 中增加总人数（stotal）和班长两个字段
-- stotal: 班级总人数，整数类型
-- monitor: 班长，可变长字符串，存储班长姓名
-- ============================================================================
ALTER TABLE Class
    ADD COLUMN stotal  INT          NULL DEFAULT 0  COMMENT '班级总人数',
    ADD COLUMN monitor VARCHAR(10)  NULL             COMMENT '班长';

-- 验证修改结果
DESCRIBE Class;

-- ============================================================================
-- 2. 建立不带参数的存储过程 p1：选择所有年龄<21岁的男同学
-- ============================================================================
DELIMITER //

CREATE PROCEDURE p1()
BEGIN
    SELECT *
    FROM Student
    WHERE Sage < 21
        AND Ssex = '男';
END //

DELIMITER ;

-- ============================================================================
-- 3. 建立带有参数的存储过程 p2：
--    根据用户传递的学号参数，显示与该学生同龄的所有同学
-- ============================================================================
DELIMITER //

CREATE PROCEDURE p2(IN p_sno CHAR(8))
BEGIN
    DECLARE target_age TINYINT;

    -- 获取目标学生的年龄
    SELECT Sage INTO target_age
    FROM Student
    WHERE Sno = p_sno;

    -- 查询与该学生同龄的所有同学（包括该学生自己）
    SELECT *
    FROM Student
    WHERE Sage = target_age;
END //

DELIMITER ;

-- ============================================================================
-- 4. 使用 CALL 分别调用 p1、p2，并显示结果
-- ============================================================================

-- 调用存储过程 p1（无参数）
CALL p1();

-- 调用存储过程 p2（传入学号参数）
CALL p2('20190101');

